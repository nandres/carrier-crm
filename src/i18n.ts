const DICTS: Record<Lang, Record<Key, string>> = { en, es };

const STATIONS: Record<Station, Record<Lang, string>> = {
  proposal: { en: 'Proposals', es: 'Propuestas' },
  invoiced: { en: 'Invoiced', es: 'Facturadas' },
  due: { en: 'Due soon', es: 'Por vencer' },
  overdue: { en: 'Overdue', es: 'Atrasadas' },
  paid: { en: 'Paid', es: 'Cobradas' },
  cancelled: { en: 'Cancelled', es: 'Canceladas' },
};

const KINDS: Record<ActivityKind, Record<Lang, string>> = {
  note: { en: 'Note', es: 'Nota' },
  call: { en: 'Call', es: 'Llamada' },
  email: { en: 'Email', es: 'Correo' },
  reminder: { en: 'Reminder', es: 'Recordatorio' },
  system: { en: 'Update', es: 'Cambio' },
};

export function resolveText(text: Text, lang: Lang): string {
  return typeof text === 'string' ? text : text[lang];
}

/** Dollars for everyone; separators follow the language. Cents only when they exist. */
export function money(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === 'es' ? 'es-PY' : 'en-US', {
    style: 'currency',
    currency: 'USD',
    currencyDisplay: 'narrowSymbol',
    minimumFractionDigits: Number.isInteger(value) ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(value);
}

export function useT() {
  const lang = useCrm((state) => state.lang);
  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) => {
      let text = DICTS[lang][key];
      if (vars) for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
      return text;
    },
    [lang],
  );
  return {
    t,
    lang,
    tx: useCallback((text: Text) => resolveText(text, lang), [lang]),
    stationName: useCallback((station: Station) => STATIONS[station][lang], [lang]),
    kindName: useCallback((kind: ActivityKind) => KINDS[kind][lang], [lang]),
    date: useCallback(
      (iso: string | Date, options: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short' }) =>
        new Intl.DateTimeFormat(lang === 'es' ? 'es' : 'en-GB', options).format(new Date(iso)),
      [lang],
    ),
    money: useCallback((value: number) => money(value, lang), [lang]),
  };
}
